#!/usr/bin/env python3
"""Bakes ui/index.html into src/ui_index.h as a gzipped byte array.

The page is served straight out of flash with Content-Encoding: gzip, so there
is no filesystem upload step and no separate asset to keep in sync with the
firmware. Deliberately no minifier: gzip already collapses the whitespace, and
a regex-based minifier on hand-written JS is a good way to ship a broken page.

Runs automatically as a PlatformIO pre-build step, or by hand:
    python3 tools/gen_ui.py
"""
import gzip
import pathlib
import sys

def _root() -> pathlib.Path:
    # Run directly, __file__ points at tools/. Run by PlatformIO, SCons execs
    # this without __file__, so ask the build environment where the project is.
    if "__file__" in globals():
        return pathlib.Path(__file__).resolve().parent.parent
    try:
        Import("env")                                  # noqa: F821  (SCons builtin)
        return pathlib.Path(env["PROJECT_DIR"])        # noqa: F821
    except Exception:
        return pathlib.Path.cwd()


ROOT = _root()
SRC = ROOT / "ui" / "index.html"
DST = ROOT / "src" / "ui_index.h"


def build() -> int:
    if not SRC.exists():
        print(f"gen_ui: {SRC} is missing", file=sys.stderr)
        return 1

    raw = SRC.read_bytes()
    # mtime=0 keeps the output byte-identical for identical input, so an
    # unchanged page doesn't churn the header and force a rebuild.
    packed = gzip.compress(raw, compresslevel=9, mtime=0)

    lines = [
        "// Generated by tools/gen_ui.py — do not edit.",
        "// Source: ui/index.html",
        f"// {len(raw)} bytes -> {len(packed)} bytes gzipped",
        "#pragma once",
        "#include <pgmspace.h>",
        "",
        f"static const size_t UI_INDEX_GZ_LEN = {len(packed)};",
        "static const uint8_t UI_INDEX_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(packed), 16):
        chunk = packed[i:i + 16]
        lines.append("  " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    out = "\n".join(lines) + "\n"

    if DST.exists() and DST.read_text() == out:
        print(f"gen_ui: up to date ({len(packed)} bytes gzipped)")
        return 0

    DST.write_text(out)
    print(f"gen_ui: {SRC.name} {len(raw)}B -> {len(packed)}B gzipped "
          f"({100 * len(packed) / len(raw):.0f}%)")
    return 0


if __name__ == "__main__":
    sys.exit(build())
else:
    # Imported by PlatformIO as a pre-build extra_script.
    build()
